"""Stage the installable Tactical pack and build its zip.

    python tools/stage_pack.py <native gear/meshes folder> <stage folder> [zip]

Copies this pack (mod.json, scripts/, the top-level .md/.txt) and the native
meshes listed in tools/assets-manifest.txt (generate_assemblies.py) into
<stage>/assets/models/, unchanged. Each mesh gets <file>.opaque listing all
its pictures: the native renderer never treats texture alpha as opacity, only
corner alpha (gevr_tactical_mesh.c draws untinted pictures in the opaque
pass), and docs/mod-system.md's .opaque list gives C10 the same rule.

When gear/optics is available, stage the native profiles and lens-ready
housings used by those same parts, including folded housings. Write a Lua
index for the pack to use on engines that support mod.attach.optic.

The meshes are Tactical's assets and stay out of Git; this tool reads them
from the native build's folder. It writes files.sha256 for the staged
campaign. With [zip], it also writes the zip the launcher installs.
"""
import shutil
import struct
import sys
from pathlib import Path

PACK = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PACK / "tools"))
from validate_pack import build_zip, shipped, validate, write_hashes  # noqa: E402


def stage_mesh(source, dest, pictures):
    shutil.copyfile(source, dest)
    dest.with_name(dest.name + ".opaque").write_text(
        " ".join(str(i) for i in range(pictures)) + "\n", encoding="ascii", newline="\n")
    return dest.stat().st_size


def picture_count(path):
    with path.open("rb") as src:
        header = src.read(12)
    if len(header) != 12 or header[:8] not in (b"GEVRWPN1", b"GEVRWPN2"):
        raise ValueError(f"{path}: not a native mesh")
    return struct.unpack_from("<I", header, 8)[0]


def stage_optics(optics, stage, mesh_names):
    models = stage / "assets" / "models"
    entries = []
    for profile in sorted(optics.glob("*.opt")):
        stem = profile.stem
        standard = f"{stem}.bin"
        if standard not in mesh_names:
            continue
        housing = f"{stem}-optic.bin"
        source = optics / standard
        if not source.is_file():
            raise ValueError(f"{profile}: missing native optic housing {source}")
        stage_mesh(source, models / housing, picture_count(source))
        shutil.copyfile(profile, models / profile.name)
        entry = f'  ["{standard}"] = {{ model = "{housing}", profile = "{profile.name}"'
        folded = optics / f"{stem}-folded.bin"
        if folded.is_file():
            stage_mesh(folded, models / folded.name, picture_count(folded))
            entry += f', folded = "{folded.name}"'
        entries.append(entry + " },")
    if entries:
        index = stage / "scripts" / "tactical" / "optic_assets.lua"
        index.write_text("\n".join([
            "-- Generated by tools/stage_pack.py from the native optic assets.",
            "return {", *entries, "}", "",
        ]), encoding="ascii", newline="\n")
    return len(entries)


def main():
    meshes, stage = Path(sys.argv[1]), Path(sys.argv[2])
    out = Path(sys.argv[3]) if len(sys.argv) > 3 else None
    problems = validate(PACK)
    if problems:
        raise SystemExit("\n".join(problems))
    if stage.exists():
        shutil.rmtree(stage)
    for f in shipped(PACK):
        dest = stage / f.relative_to(PACK)
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(f, dest)
    models = stage / "assets" / "models"
    models.mkdir(parents=True, exist_ok=True)
    total = 0
    mesh_names = set()
    for line in (PACK / "tools" / "assets-manifest.txt").read_text().splitlines():
        name, pictures = line.split()
        total += stage_mesh(meshes / name, models / name, int(pictures))
        mesh_names.add(name)
    optics = stage_optics(meshes.parent / "optics", stage, mesh_names)
    print(f"staged {stage}: {len(mesh_names)} standard meshes ({total / 2**20:.0f} MiB), {optics} native optics")
    problems = validate(stage)
    if problems:
        raise SystemExit("\n".join(problems))
    if out is not None:
        build_zip(out, stage)
    else:
        write_hashes(stage, shipped(stage))


if __name__ == "__main__":
    main()
