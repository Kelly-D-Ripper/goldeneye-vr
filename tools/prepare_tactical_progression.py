"""Compile the reviewed Workshop unlock TSVs into stable-ID game tables."""
import csv
import json
from pathlib import Path
import sys


def read(path):
    with path.open(encoding='utf-8-sig', newline='') as f:
        return list(csv.DictReader(f, delimiter='\t'))


def text(value):
    return json.dumps(value.replace('—', '-'), ensure_ascii=True)


def generate(folder, output):
    guns = read(folder / 'gun-unlocks.tsv')
    kits = [r for r in read(folder / 'unlock-kits.tsv') if r['Primary route'] == 'Standard kit']
    parts = read(folder / 'part-unlocks.tsv')
    keys = {r['Gun']: int(r['Workshop key']) for r in guns}
    assert len(keys) == 42 and max(keys.values()) < 64
    assert len({r['Stable catalogue ID'] for r in parts}) == len(parts)
    pk = [p for p in parts if p['Stock on'] == 'PKM' and int(p['Capacity'] or 0) >= 60]
    assert len(pk) == 1
    known = []
    table = ['/* Generated by tools/prepare_tactical_progression.py. */',
             f'#define PROGRESS_PKM_BOX {text(pk[0]["Stable catalogue ID"])}',
             'static const ProgressGunRule gunRules[] = {']
    for gun in sorted(guns, key=lambda g: int(g['Workshop key'])):
        table.append(f'    [{gun["Workshop key"]}] = {{{text(gun["Gun"])}, {gun["Minimum total clears for reserve eligibility"]}}},')
    table += ['};', '', 'static const ProgressKitRule kitRules[] = {']
    for kit in kits:
        k = kit['Kit ID']
        mask = sum(1 << keys[g] for g in kit['Eligible host guns'].split('; '))
        members = sorted(p['Stable catalogue ID'] for p in parts if p['Unlock kit ID'] == k)
        assert members and mask and len(members) == int(kit['Catalogue records'])
        table.append(f'    {{{text(kit["Kit"])}, UINT64_C(0x{mask:x}), {len(known)}, {len(members)}, {kit["Successful clears (proposed)"]}}},')
        known.extend(members)
    assert len(set(known)) == len(known) == sum(p['Primary route'] == 'Standard kit' for p in parts)
    table += ['};', '', 'static const char kitPartIds[][25] = {']
    for start in range(0, len(known), 3):
        table.append('    ' + ', '.join(map(text, known[start:start + 3])) + ',')
    table += ['};', '', 'static const char internalIds[][25] = {']
    internal = sorted(p['Stable catalogue ID'] for p in parts if p['Primary route'] == 'Automatic or built in')
    for start in range(0, len(internal), 3):
        table.append('    ' + ', '.join(map(text, internal[start:start + 3])) + ',')
    output.write_text('\n'.join([*table, '};', '']), encoding='ascii')


if __name__ == '__main__':
    generate(Path(sys.argv[1]), Path(sys.argv[2]))
